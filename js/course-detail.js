// courses.js uses this exact course name in the URL.
data['Full Stack Web Development (MERN)'] = data['MERN Stack'];


// =========================================================
// GET COURSE FROM URL
// =========================================================

const params = new URLSearchParams(window.location.search);

const requestedCourse =
    params.get('course') || 'Full Stack Web Development (MERN)';


// =========================================================
// SELECT COURSE
// =========================================================

const course =
    data[requestedCourse] || data['MERN Stack'];


// =========================================================
// ELEMENTS
// =========================================================

const detailTitle =
    document.querySelector('#detailTitle');

const detailDesc =
    document.querySelector('#detailDesc');

const detailImage =
    document.querySelector('#detailImage');

const curriculum =
    document.querySelector('#courseCurriculum');


// =========================================================
// COURSE BASIC INFORMATION
// =========================================================

if (detailTitle) {
    detailTitle.textContent = course.title;
}

if (detailDesc) {
    detailDesc.textContent = course.description;
}

if (detailImage) {
    detailImage.src = `assets/images/${course.image}`;
    detailImage.alt =
        `${course.title} training at Million Technology`;
}


// =========================================================
// COURSE INFORMATION PANEL
// =========================================================

const infoFields = {
    Duration: course.duration,
    Level: course.level,
    Mode: course.mode,
    Certification: course.certification,
    Projects: course.projects
};

Object.entries(infoFields).forEach(([key, value]) => {

    const element =
        document.querySelector(`[data-info="${key}"]`);

    if (element) {
        element.textContent = value;
    }

});


// =========================================================
// RENDER CURRICULUM
// =========================================================

if (curriculum) {

    curriculum.innerHTML = course.modules
        .map((module, index) => {

            const number =
                String(index + 1).padStart(2, '0');

            return `
                <div class="module">

                    <button
                        class="module-toggle"
                        type="button"
                    >

                        <span>
                            <small>${number}</small>
                            ${module.title}
                        </span>

                        <i class="fa-solid fa-plus"></i>

                    </button>

                    <div class="module-content">

                        <ul>
                            ${module.topics
                                .map(topic => `
                                    <li>${topic}</li>
                                `)
                                .join('')}
                        </ul>

                    </div>

                </div>
            `;

        })
        .join('');
}


// =========================================================
// ACCORDION
// =========================================================

const moduleButtons =
    document.querySelectorAll('.module-toggle');


moduleButtons.forEach((button) => {

    button.addEventListener('click', () => {

        const module =
            button.closest('.module');

        if (!module) return;

        const content =
            module.querySelector('.module-content');

        const icon =
            button.querySelector('i');

        const isOpen =
            module.classList.contains('open');


        // Close all modules
        document.querySelectorAll('.module')
            .forEach((item) => {

                item.classList.remove('open');

                const itemContent =
                    item.querySelector('.module-content');

                const itemIcon =
                    item.querySelector('.module-toggle i');


                if (itemContent) {
                    itemContent.style.maxHeight = null;
                }


                if (itemIcon) {

                    itemIcon.classList.remove(
                        'fa-minus'
                    );

                    itemIcon.classList.add(
                        'fa-plus'
                    );

                }

            });


        // Open clicked module
        if (!isOpen) {

            module.classList.add('open');


            if (content) {
                content.style.maxHeight =
                    content.scrollHeight + 'px';
            }


            if (icon) {

                icon.classList.remove(
                    'fa-plus'
                );

                icon.classList.add(
                    'fa-minus'
                );

            }

        }

    });

});